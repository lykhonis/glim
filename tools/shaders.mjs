// @ts-check
// Single-source shaders (glass plan D2). GLSL 450 in packages/glim-gpu/shaders
// is the only hand-edited source; Metal and WGSL are generated and committed,
// so a normal build needs no extra tools. CI runs `check` to keep them aligned.
//
//   node tools/shaders.mjs install   build the pinned tools into build/shader-tools
//   node tools/shaders.mjs gen       regenerate the committed MSL and WGSL
//   node tools/shaders.mjs check     fail if any committed output is stale
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// Generated text depends on exact tool versions; CI and local share these pins.
const pins = { khronos: "vulkan-sdk-1.4.363.0", naga: "30.0.1" };
const prefix = path.join(root, "build", "shader-tools", `${pins.khronos}-naga${pins.naga}`);
const bin = (/** @type {string} */ name) => path.join(prefix, "bin", name);

const sourceDir = path.join(root, "packages/glim-gpu/shaders");
const metalDir = path.join(root, "packages/glim-gpu-metal/shaders");
const wgslDir = path.join(root, "packages/glim-gpu-webgpu/shaders");
const stages = /** @type {const} */ (["vert", "frag"]);

/** @param {string} message @returns {never} */
function fail(message) {
  console.error(message);
  process.exit(1);
}

/** @param {string} cmd @param {string[]} args @param {NodeJS.ProcessEnv} [env] */
function run(cmd, args, env) {
  return execFileSync(cmd, args, { env: { ...process.env, ...env }, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
}

/** @param {string} repo @param {string} name @param {string[]} defines */
function buildKhronos(repo, name, defines) {
  const src = path.join(prefix, "src", name);
  if (!existsSync(src)) {
    run("git", ["clone", "--depth", "1", "--branch", pins.khronos, `https://github.com/KhronosGroup/${repo}`, src]);
  }
  const out = path.join(src, "build");
  run("cmake", ["-S", src, "-B", out, "-DCMAKE_BUILD_TYPE=Release", `-DCMAKE_INSTALL_PREFIX=${prefix}`, ...defines]);
  run("cmake", ["--build", out, "--target", "install", "--parallel"]);
}

function install() {
  mkdirSync(prefix, { recursive: true });
  if (!existsSync(bin("glslang"))) {
    console.log(`building glslang ${pins.khronos}`);
    buildKhronos("glslang", "glslang", ["-DENABLE_OPT=OFF", "-DGLSLANG_TESTS=OFF", "-DENABLE_HLSL=OFF"]);
  }
  if (!existsSync(bin("spirv-cross"))) {
    console.log(`building SPIRV-Cross ${pins.khronos}`);
    buildKhronos("SPIRV-Cross", "spirv-cross", ["-DSPIRV_CROSS_ENABLE_TESTS=OFF", "-DSPIRV_CROSS_SHARED=OFF"]);
  }
  if (!existsSync(bin("naga"))) {
    console.log(`installing naga-cli ${pins.naga}`);
    // A pinned default toolchain may be too old; rustup honours this, plain cargo ignores it.
    run("cargo", ["install", "naga-cli", "--version", pins.naga, "--locked", "--root", prefix], {
      RUSTUP_TOOLCHAIN: process.env.RUSTUP_TOOLCHAIN ?? "stable",
    });
  }
  console.log(`shader tools ready in ${path.relative(root, prefix)}`);
}

/** Shader names that have both stages in the source dir. */
function shaderNames() {
  const files = readdirSync(sourceDir);
  const names = files.filter((f) => f.endsWith(".vert")).map((f) => f.slice(0, -5));
  for (const n of names) if (!files.includes(`${n}.frag`)) fail(`${n}.vert has no ${n}.frag`);
  return names.sort();
}

/** @param {string} name @param {string} stage */
function banner(name, stage) {
  const comment = `Generated by tools/shaders.mjs from packages/glim-gpu/shaders/${name}.${stage}. Do not edit.`;
  return `// ${comment}\n`;
}

/** @param {string} outMetal @param {string} outWgsl */
function generate(outMetal, outWgsl) {
  for (const tool of ["glslang", "spirv-cross", "naga"]) {
    if (!existsSync(bin(tool))) fail(`missing ${bin(tool)}; run: node tools/shaders.mjs install`);
  }
  const tmp = mkdtempSync(path.join(os.tmpdir(), "glim-shaders-"));
  /** @type {string[]} */
  const written = [];
  try {
    for (const name of shaderNames()) {
      for (const stage of stages) {
        const glsl = path.join(sourceDir, `${name}.${stage}`);
        const spv = path.join(tmp, `${name}.${stage}.spv`);
        run(bin("glslang"), ["-V", "--target-env", "vulkan1.1", glsl, "-o", spv]);
        const entry = stage === "vert" ? "vs_main" : "fs_main";
        const msl = run(bin("spirv-cross"), [
          spv, "--msl", "--msl-version", "20100", "--msl-decoration-binding",
          "--rename-entry-point", "main", entry, stage,
        ]);
        const metalFile = `${name}.${stage}.metal`;
        writeFileSync(path.join(outMetal, metalFile), banner(name, stage) + msl);
        const wgslFile = `${name}.${stage}.wgsl`;
        const wgslTmp = path.join(tmp, wgslFile);
        run(bin("naga"), ["--keep-coordinate-space", spv, wgslTmp]);
        const wgsl = readFileSync(wgslTmp, "utf8").replace(/\bfn main\(/, `fn ${entry}(`);
        writeFileSync(path.join(outWgsl, wgslFile), banner(name, stage) + wgsl);
        written.push(metalFile, wgslFile);
      }
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  return written;
}

/** Generated files carry the banner; hand-written ones do not. */
function generatedIn(/** @type {string} */ dir) {
  return readdirSync(dir).filter((f) =>
    readFileSync(path.join(dir, f), "utf8").startsWith("// Generated by tools/shaders.mjs"),
  );
}

function check() {
  const tmp = mkdtempSync(path.join(os.tmpdir(), "glim-shaders-check-"));
  const outMetal = path.join(tmp, "metal");
  const outWgsl = path.join(tmp, "wgsl");
  mkdirSync(outMetal);
  mkdirSync(outWgsl);
  try {
    generate(outMetal, outWgsl);
    let stale = 0;
    for (const [dir, out] of [[metalDir, outMetal], [wgslDir, outWgsl]]) {
      const want = readdirSync(out);
      for (const f of want) {
        const committed = path.join(dir, f);
        if (!existsSync(committed) || readFileSync(committed, "utf8") !== readFileSync(path.join(out, f), "utf8")) {
          console.error(`stale: ${path.relative(root, committed)}`);
          stale++;
        }
      }
      for (const f of generatedIn(dir)) {
        if (!want.includes(f)) {
          console.error(`orphan: ${path.relative(root, path.join(dir, f))} (no GLSL source)`);
          stale++;
        }
      }
    }
    if (stale) fail(`${stale} generated shader file(s) out of date; run: node tools/shaders.mjs gen`);
    console.log("shaders: generated MSL and WGSL match their GLSL sources");
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

const command = process.argv[2];
if (command === "install") install();
else if (command === "gen") console.log(`wrote ${generate(metalDir, wgslDir).length} files`);
else if (command === "check") check();
else fail("usage: node tools/shaders.mjs install | gen | check");
